alter table bind_attempts      enable row level security;   -- 不開任何 policy：只能透過函式寫入

-- 分隊清單、案件種類：登入者都能讀
create policy squads_read     on squads     for select to authenticated using (true);
create policy case_types_read on case_types for select to authenticated using (true);
create policy squads_admin    on squads     for all    to authenticated using (is_super_admin()) with check (is_super_admin());

-- 隊員：讀自己分隊；幹部管理自己分隊
create policy members_read   on members for select to authenticated using (can_read_squad(squad_id));
create policy members_insert on members for insert to authenticated with check (can_admin_squad(squad_id));
create policy members_update on members for update to authenticated using (can_admin_squad(squad_id)) with check (can_admin_squad(squad_id));
create policy members_delete on members for delete to authenticated using (can_admin_squad(squad_id));

-- 排班：讀自己分隊；自己新增/刪除自己的班；幹部可管理全分隊
create policy shifts_read   on shifts for select to authenticated using (can_read_squad(squad_id));
create policy shifts_insert on shifts for insert to authenticated
  with check ((member_id = my_member_id() and squad_id = my_squad_id()) or can_admin_squad(squad_id));
create policy shifts_update on shifts for update to authenticated
  using (member_id = my_member_id() or can_admin_squad(squad_id))
  with check ((member_id = my_member_id() and squad_id = my_squad_id()) or can_admin_squad(squad_id));
create policy shifts_delete on shifts for delete to authenticated
  using (member_id = my_member_id() or can_admin_squad(squad_id));

-- 公差/會議：讀自己分隊；幹部發布與管理
create policy tasks_read  on tasks for select to authenticated using (can_read_squad(squad_id));
create policy tasks_write on tasks for all    to authenticated using (can_admin_squad(squad_id)) with check (can_admin_squad(squad_id));

-- 報名：讀自己分隊任務的報名；自己報名自己；幹部可代為報名/修改
create policy registrations_read on registrations for select to authenticated
  using (exists (select 1 from tasks t where t.id = task_id and can_read_squad(t.squad_id)));
create policy registrations_insert on registrations for insert to authenticated
  with check (exists (select 1 from tasks t where t.id = task_id and (
    (member_id = my_member_id() and t.squad_id = my_squad_id()) or can_admin_squad(t.squad_id))));
create policy registrations_update on registrations for update to authenticated
  using (exists (select 1 from tasks t where t.id = task_id and (member_id = my_member_id() or can_admin_squad(t.squad_id))))
  with check (exists (select 1 from tasks t where t.id = task_id and (
    (member_id = my_member_id() and t.squad_id = my_squad_id()) or can_admin_squad(t.squad_id))));
create policy registrations_delete on registrations for delete to authenticated
  using (exists (select 1 from tasks t where t.id = task_id and (member_id = my_member_id() or can_admin_squad(t.squad_id))));

-- 協勤紀錄：讀自己分隊（全隊紀錄）；自己寫自己的；幹部可修改全分隊
create policy assistance_read on assistance_records for select to authenticated using (can_read_squad(squad_id));
create policy assistance_insert on assistance_records for insert to authenticated
  with check ((member_id = my_member_id() and squad_id = my_squad_id()) or can_admin_squad(squad_id));
create policy assistance_update on assistance_records for update to authenticated
  using (member_id = my_member_id() or can_admin_squad(squad_id))
  with check ((member_id = my_member_id() and squad_id = my_squad_id()) or can_admin_squad(squad_id));
create policy assistance_delete on assistance_records for delete to authenticated
  using (member_id = my_member_id() or can_admin_squad(squad_id));

-- 案件：跟著所屬協勤紀錄的權限
create policy cases_read on assistance_cases for select to authenticated
  using (exists (select 1 from assistance_records r where r.id = record_id and can_read_squad(r.squad_id)));
create policy cases_write on assistance_cases for all to authenticated
  using (exists (select 1 from assistance_records r where r.id = record_id and (r.member_id = my_member_id() or can_admin_squad(r.squad_id))))
  with check (exists (select 1 from assistance_records r where r.id = record_id and (r.member_id = my_member_id() or can_admin_squad(r.squad_id))));

-- 零用金：讀自己分隊；幹部記帳
create policy fund_read  on fund_entries for select to authenticated using (can_read_squad(squad_id));
create policy fund_write on fund_entries for all    to authenticated using (can_admin_squad(squad_id)) with check (can_admin_squad(squad_id));


