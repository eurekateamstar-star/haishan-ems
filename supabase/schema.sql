-- =====================================================================
-- 防止權限提升：分隊幹部不能把人升成系統管理員，也不能把人搬到別的分隊
-- 也不能停權或降級自己（避免把自己鎖在外面）
-- =====================================================================
create or replace function public.guard_member_update() returns trigger
language plpgsql set search_path = public as $$   -- 以呼叫者身分執行，current_user 才會是 authenticated
begin
  if current_user in ('postgres', 'service_role') then
    return new;
  end if;
  if not is_super_admin() then
    if new.role = 'super_admin' and old.role is distinct from 'super_admin' then
      raise exception '只有系統管理員可以指派系統管理員';
    end if;
    if old.role = 'super_admin' and new.role is distinct from old.role then
      raise exception '只有系統管理員可以變更系統管理員';
    end if;
    if new.squad_id <> old.squad_id then
      raise exception '只有系統管理員可以調動分隊';
    end if;
  end if;
  if old.id = my_member_id() and (new.is_suspended or new.role < old.role) then
    raise exception '不能停權或降級自己';
  end if;
  new.updated_at := now();
  return new;
end $$;
create trigger members_guard before update on members
  for each row execute function guard_member_update();

create or replace function public.guard_member_insert() returns trigger
language plpgsql set search_path = public as $$   -- 以呼叫者身分執行，current_user 才會是 authenticated
begin
  if current_user in ('postgres', 'service_role') then return new; end if;
  if new.role = 'super_admin' and not is_super_admin() then
    raise exception '只有系統管理員可以指派系統管理員';
  end if;
  new.line_user_id := null;   -- 綁定只能透過 bind_member()
  return new;
end $$;
create trigger members_guard_insert before insert on members
  for each row execute function guard_member_insert();

create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at := now(); return new; end $$;
create trigger registrations_touch before update on registrations for each row execute function touch_updated_at();
create trigger assistance_touch    before update on assistance_records for each row execute function touch_updated_at();


-- =====================================================================
-- 綁定流程（首次 LINE 登入）
-- =====================================================================

-- 目前 LINE 帳號的綁定狀態
create or replace function public.my_binding() returns jsonb
language sql stable security definer set search_path = public as $$
  select case
    when jwt_line_user_id() is null then jsonb_build_object('status', 'no_login')
    when m.id is null then jsonb_build_object('status', 'unbound')
    when m.is_suspended then jsonb_build_object('status', 'suspended', 'name', m.name)
    else jsonb_build_object('status', 'bound', 'member_id', m.id, 'squad_id', m.squad_id,
                            'name', m.name, 'role', m.role)
  end
  from (select 1) x
  left join members m on m.line_user_id = jwt_line_user_id()
$$;

-- 綁定時可選的名單：該分隊尚未綁定、未停權的隊員（只回傳姓名）
create or replace function public.list_bindable_members(p_squad_id smallint)
returns table (id uuid, name text, duty_group text)
language sql stable security definer set search_path = public as $$
  select m.id, m.name, m.duty_group from members m
  where jwt_line_user_id() is not null
    and m.squad_id = p_squad_id and m.line_user_id is null and not m.is_suspended
  order by m.sort_order, m.name
$$;

-- 以生日驗證後綁定；24 小時內失敗 5 次就鎖住
create or replace function public.bind_member(p_member_id uuid, p_birthday date,
                                              p_display_name text default null, p_picture_url text default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_line text := jwt_line_user_id();
  v_fails int;
  v_member members;
begin
  if v_line is null then
    return jsonb_build_object('ok', false, 'message', '請先用 LINE 登入');
  end if;
  if exists (select 1 from members where line_user_id = v_line) then
    return jsonb_build_object('ok', false, 'message', '這個 LINE 帳號已經綁定過了');
  end if;

  select count(*) into v_fails from bind_attempts
  where line_user_id = v_line and not success and created_at > now() - interval '24 hours';
  if v_fails >= 5 then
    return jsonb_build_object('ok', false, 'message', '驗證失敗次數過多，請 24 小時後再試，或請分隊幹部協助');
  end if;

  select * into v_member from members where id = p_member_id for update;
  if v_member.id is null or v_member.is_suspended or v_member.line_user_id is not null then
    return jsonb_build_object('ok', false, 'message', '這位隊員無法綁定，請聯絡分隊幹部');
  end if;
  if v_member.birthday is null then
    return jsonb_build_object('ok', false, 'message', '這位隊員尚未登錄生日，請聯絡分隊幹部');
  end if;
  if v_member.birthday <> p_birthday then
    insert into bind_attempts (line_user_id, member_id, success) values (v_line, p_member_id, false);
    return jsonb_build_object('ok', false, 'message',
      case when v_fails >= 4 then '生日不正確，已達 5 次上限，請 24 小時後再試，或請分隊幹部協助'
           else format('生日不正確（還可以再試 %s 次）', 4 - v_fails) end);
  end if;

  update members set line_user_id = v_line,
                     line_display_name = left(p_display_name, 100),
                     line_picture_url = left(p_picture_url, 500),
                     bound_at = now()
  where id = p_member_id;
  insert into bind_attempts (line_user_id, member_id, success) values (v_line, p_member_id, true);
  return jsonb_build_object('ok', true, 'member_id', p_member_id, 'name', v_member.name);
end $$;

-- 幹部解除某隊員的 LINE 綁定（換手機、綁錯人時使用）
create or replace function public.unbind_member(p_member_id uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_squad smallint;
begin
  select squad_id into v_squad from members where id = p_member_id;
  if v_squad is null or not can_admin_squad(v_squad) then
    return jsonb_build_object('ok', false, 'message', '沒有權限');
  end if;
  update members set line_user_id = null, line_display_name = null, line_picture_url = null, bound_at = null
  where id = p_member_id;
  return jsonb_build_object('ok', true);
end $$;


-- =====================================================================
-- 協勤紀錄：一次存入紀錄與案件（新增或修改），整筆成功或整筆失敗
--   p_record: {"id"?, "member_id"?, "date", "shift_start", "shift_end"}
--   p_cases:  [{"case_start","case_end","district","address","case_type","description","rescued_count"}, ...]
--   以呼叫者身分執行，所以一樣受 RLS 保護
-- =====================================================================
create or replace function public.save_assistance(p_record jsonb, p_cases jsonb default '[]')
returns uuid
language plpgsql security invoker set search_path = public as $$
declare
  v_id     uuid := nullif(p_record->>'id', '')::uuid;
  v_member uuid := coalesce(nullif(p_record->>'member_id', '')::uuid, my_member_id());
  v_squad  smallint;
  v_type   text := case when jsonb_array_length(coalesce(p_cases, '[]')) > 0 then '急救護-救護勤務' else '待命協勤' end;
  v_rows   int;
begin
  select squad_id into v_squad from members where id = v_member;
  if v_squad is null then raise exception '找不到隊員'; end if;

  if v_id is null then
    insert into assistance_records (squad_id, member_id, date, shift_start, shift_end, record_type)
    values (v_squad, v_member, (p_record->>'date')::date, (p_record->>'shift_start')::time,
            (p_record->>'shift_end')::time, v_type)
    returning id into v_id;
  else
    update assistance_records
       set date = (p_record->>'date')::date, shift_start = (p_record->>'shift_start')::time,
           shift_end = (p_record->>'shift_end')::time, record_type = v_type
     where id = v_id;
    get diagnostics v_rows = row_count;
    if v_rows = 0 then raise exception '找不到這筆紀錄，或沒有修改權限'; end if;
    delete from assistance_cases where record_id = v_id;
  end if;

  insert into assistance_cases (record_id, seq, case_start, case_end, district, address, case_type, description, rescued_count)
  select v_id, c.ord::int,
         nullif(c.v->>'case_start', '')::time, nullif(c.v->>'case_end', '')::time,
         c.v->>'district', c.v->>'address', c.v->>'case_type', c.v->>'description',
         coalesce((c.v->>'rescued_count')::int, 0)
  from jsonb_array_elements(coalesce(p_cases, '[]')) with ordinality as c(v, ord);

  return v_id;
end $$;

-- =====================================================================
-- 統計：時數、出勤時數、總出勤件數、各類案件件數
-- 在資料庫算好，手機只拿結果（取代舊平台下載全部紀錄再算）
-- =====================================================================
create or replace function public.hours_between(a time, b time) returns numeric
language sql immutable as $$
  -- 跨午夜（例如 23:40 → 00:30）自動加 24 小時
  select case when a is null or b is null then 0
              else round((extract(epoch from (b - a)) / 3600.0
                          + case when b < a then 24 else 0 end)::numeric, 4) end
$$;

-- 分隊排名資料（p_from、p_to 為 null 表示不限）
create or replace function public.squad_ranking(p_squad_id smallint, p_from date default null, p_to date default null)
returns table (
  member_id uuid, name text, duty_title text, sort_order int,
  hours numeric, case_hours numeric, case_count int, rescued_count int, case_type_counts jsonb
)
language sql stable security invoker set search_path = public as $$
  with recs as (
    select r.* from assistance_records r
    where r.squad_id = p_squad_id
      and (p_from is null or r.date >= p_from)
      and (p_to   is null or r.date <= p_to)
  ),
  per_member as (
    select member_id, sum(hours_between(shift_start, shift_end)) as hours
    from recs group by member_id
  ),
  cases as (
    select r.member_id, c.case_type, hours_between(c.case_start, c.case_end) as h, c.rescued_count
    from recs r join assistance_cases c on c.record_id = r.id
  ),
  per_case as (
    select member_id,
           sum(case when h > 0 and h <= 24 then h else 0 end) as case_hours,
           count(*)::int as case_count,
           sum(rescued_count)::int as rescued_count
    from cases group by member_id
  ),
  per_type as (
    select member_id, jsonb_object_agg(case_type, n) as case_type_counts
    from (select member_id, case_type, count(*)::int as n from cases where case_type is not null
          group by member_id, case_type) t
    group by member_id
  )
  select m.id, m.name, m.duty_title, m.sort_order,
         round(coalesce(pm.hours, 0), 1),
         round(coalesce(pc.case_hours, 0), 1),
         coalesce(pc.case_count, 0),
         coalesce(pc.rescued_count, 0),
         coalesce(pt.case_type_counts, '{}'::jsonb)
  from members m
  left join per_member pm on pm.member_id = m.id
  left join per_case   pc on pc.member_id = m.id
  left join per_type   pt on pt.member_id = m.id
  where m.squad_id = p_squad_id
$$;

-- 個人年度統計（首頁）：今年時數、出勤次數、救出人數、各類案件
create or replace function public.my_year_stats(p_year int default extract(year from now())::int)
returns jsonb
language sql stable security invoker set search_path = public as $$
  select to_jsonb(r) - 'member_id' - 'sort_order'
  from squad_ranking(my_squad_id(), make_date(p_year, 1, 1), make_date(p_year, 12, 31)) r
  where r.member_id = my_member_id()
$$;

-- 零用金餘額與年度收支
create or replace function public.squad_fund_summary(p_squad_id smallint, p_year int default extract(year from now())::int)
returns jsonb
language sql stable security invoker set search_path = public as $$
  select jsonb_build_object(
    'balance',      coalesce(sum(income - expense), 0),
    'year_income',  coalesce(sum(income)  filter (where extract(year from date) = p_year), 0),
    'year_expense', coalesce(sum(expense) filter (where extract(year from date) = p_year), 0))
  from fund_entries where squad_id = p_squad_id
$$;

