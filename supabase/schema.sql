-- =====================================================================
-- 權限輔助函式
-- =====================================================================
create or replace function public.jwt_line_user_id() returns text
language sql stable as $$ select auth.jwt()->>'sub' $$;

-- 目前登入者（已綁定、未停權）的隊員資料
create or replace function public.me() returns members
language sql stable security definer set search_path = public as $$
  select * from members
  where line_user_id = jwt_line_user_id() and not is_suspended
  limit 1
$$;

create or replace function public.my_member_id() returns uuid
language sql stable security definer set search_path = public as $$ select (me()).id $$;

create or replace function public.my_squad_id() returns smallint
language sql stable security definer set search_path = public as $$ select (me()).squad_id $$;

create or replace function public.is_super_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((me()).role = 'super_admin', false)
$$;

-- 是否可管理某分隊（該分隊幹部或系統管理員）
create or replace function public.can_admin_squad(sq smallint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(
    (me()).role = 'super_admin'
    or ((me()).role = 'squad_admin' and (me()).squad_id = sq),
    false)
$$;

-- 是否可讀某分隊資料（自己的分隊，或系統管理員）
create or replace function public.can_read_squad(sq smallint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((me()).squad_id = sq or (me()).role = 'super_admin', false)
$$;


