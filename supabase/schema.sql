-- =====================================================================
-- 海山救護義消平台（多分隊版） — Supabase / PostgreSQL 資料庫結構
--
-- 使用方式：Supabase 後台 → SQL Editor → 貼上整份 → Run
-- 可重複執行的部分只有函式（create or replace）；資料表請只執行一次。
--
-- 登入方式：LINE LIFF → Cloudflare Worker 驗證後簽發 JWT
--   JWT 的 sub = LINE userId，role = authenticated
--   資料庫用 auth.jwt()->>'sub' 對應到 members.line_user_id
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 分隊
-- ---------------------------------------------------------------------
create table squads (
  id          smallint generated by default as identity primary key,
  name        text not null unique,
  sort_order  int  not null default 0,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. 隊員
--    role: member 隊員 / squad_admin 分隊幹部 / super_admin 系統管理員
--    birthday 只用於首次綁定驗證，其他隊員讀不到（見下方欄位權限）
-- ---------------------------------------------------------------------
create type member_role as enum ('member', 'squad_admin', 'super_admin');

create table members (
  id                uuid primary key default gen_random_uuid(),
  squad_id          smallint not null references squads(id),
  name              text not null,
  birthday          date,
  duty_group        text,                         -- 小隊（第一小隊、幹部…）
  duty_title        text not null default '隊員',  -- 職稱
  role              member_role not null default 'member',
  is_suspended      boolean not null default false,
  join_date         date,
  emt_level         text,
  emt_expiry        date,
  honor_expiry      date,
  duty_count        int not null default 0,
  medals            jsonb not null default '{}',   -- {"志工菁英": "113年", "衛福部 金": "112年", ...}
  historic_hours    jsonb not null default '{}',   -- {"93": 120, "94": 85.5, ...}（民國年 → 時數，今年以前）
  sort_order        int not null default 999,
  line_user_id      text unique,                   -- 綁定的 LINE userId
  line_display_name text,
  line_picture_url  text,
  bound_at          timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  unique (squad_id, name)
);
create index members_squad_idx on members (squad_id);

-- ---------------------------------------------------------------------
-- 3. 排班
-- ---------------------------------------------------------------------
create table shifts (
  id          uuid primary key default gen_random_uuid(),
  squad_id    smallint not null references squads(id),
  member_id   uuid not null references members(id) on delete cascade,
  date        date not null,
  start_hour  text not null,   -- 與舊平台相同：'17'、'19' 這類字串
  end_hour    text not null,
  created_at  timestamptz not null default now()
);
create index shifts_squad_date_idx on shifts (squad_id, date);

-- ---------------------------------------------------------------------
-- 4. 公差 / 會議（舊平台的 official_tasks、meeting_tasks 合併）
-- ---------------------------------------------------------------------
create table tasks (
  id           uuid primary key default gen_random_uuid(),
  squad_id     smallint not null references squads(id),
  kind         text not null check (kind in ('duty', 'meeting')),  -- duty 公差 / meeting 會議
  category     text,            -- 會議：一般會議、旅遊、聚餐
  title        text not null,
  date         date not null,
  start_time   text,
  end_time     text,
  location     text,
  note         text,
  quota        int not null default 0,
  price_adult  int not null default 0,
  price_child  int not null default 0,
  created_by   uuid references members(id) on delete set null,
  created_at   timestamptz not null default now()
);
create index tasks_squad_date_idx on tasks (squad_id, date);

-- ---------------------------------------------------------------------
-- 5. 報名
-- ---------------------------------------------------------------------
create table registrations (
  id           uuid primary key default gen_random_uuid(),
  task_id      uuid not null references tasks(id) on delete cascade,
  member_id    uuid not null references members(id) on delete cascade,
  status       text not null default '出席',
  diet         text,
  plus_adult   int not null default 0,
  plus_child   int not null default 0,
  breakdown    jsonb,
  final_price  int,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (task_id, member_id)
);
create index registrations_member_idx on registrations (member_id);

-- ---------------------------------------------------------------------
-- 6. 協勤紀錄與案件
-- ---------------------------------------------------------------------
create table assistance_records (
  id           uuid primary key default gen_random_uuid(),
  squad_id     smallint not null references squads(id),
  member_id    uuid not null references members(id) on delete cascade,
  date         date not null,
  shift_start  time not null,
  shift_end    time not null,
  record_type  text not null default '待命協勤',   -- 待命協勤 / 急救護-救護勤務
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index assistance_squad_date_idx  on assistance_records (squad_id, date);
create index assistance_member_date_idx on assistance_records (member_id, date);

create table assistance_cases (
